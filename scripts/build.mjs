import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(readFileSync(path.join(root, 'src/manifest.json'), 'utf8'));
const colors = JSON.parse(readFileSync(path.join(root, 'src/colors.json'), 'utf8'));
const checking = process.argv.includes('--check');
const source = name => readFileSync(path.join(root, 'src', name), 'utf8').trimEnd();
const logoSources = Object.fromEntries([['light', 'icon.svg'], ['dark', 'icon-dark.svg']].map(([theme, file]) => [theme,
  (() => {
    const filename = path.join(root, 'assets', file);
    const original = readFileSync(filename, 'utf8');
    let processed = 0;
    const rendered = original.replace(/data-(fill|stroke)="([a-zA-Z0-9.-]+)"(\s+)(fill|stroke)="[^"]*"/g, (match, role, key, whitespace, attribute) => {
      const value = key.split('.').reduce((object, part) => object?.[part], colors);
      if (role !== attribute || typeof value !== 'string' || !/^#[a-f0-9]{6}$/i.test(value)) throw new Error(`Invalid logo color role: ${key}`);
      processed++;
      return `data-${role}="${key}"${whitespace}${attribute}="${value}"`;
    });
    if (processed !== [...original.matchAll(/\bdata-(?:fill|stroke)=/g)].length) throw new Error(`Unprocessed color role in ${file}; place each role before its paint attribute.`);
    if (checking && original !== rendered) throw new Error(`${file} colors are stale. Run npm run build.`);
    if (!checking && original !== rendered) writeFileSync(filename, rendered);
    return rendered;
  })(),
]));
const embedSVG = svg => 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');
const logos = Object.fromEntries(Object.entries(logoSources).map(([theme, svg]) => [theme, embedSVG(svg)]));
const inlineIcons = Object.fromEntries(Object.entries(manifest.icons).map(([name, filename]) => [name,
  readFileSync(path.join(root, 'assets/icons', filename), 'utf8').trim()
    .replace(/\s*<title>[^<]*<\/title>/, '')
    .replace('<svg ', '<svg aria-hidden="true" focusable="false" '),
]));
const license = readFileSync(path.join(root, 'LICENSE'), 'utf8').trimEnd();
const licenseComment = license.split('\n').map(line => line ? `// ${line}` : '//').join('\n');
const sections = manifest.parts.map(name => {
  const body = source(name).split('\n').map(line => line ? '    ' + line : '').join('\n');
  return `    // Source: src/${name}\n${body}`;
});
const output = `${source(manifest.header)}\n\n${licenseComment}\n\n// Generated by scripts/build.mjs. Edit src/ and assets/; run npm run build.\n(function () {\n    'use strict';\n\n    // Embedded from canonical SVG assets; no runtime asset requests.\n    const COLORS = ${JSON.stringify(colors)};\n    const LOGOS = ${JSON.stringify(logos)};\n    const INLINE_ICONS = ${JSON.stringify(inlineIcons)};\n\n${sections.join('\n\n')}\n})();\n`;
const target = path.join(root, 'userscript/slim-search-highlight.user.js');
if (checking) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('Generated userscript is stale. Run npm run build.');
    process.exitCode = 1;
  } else console.log('Generated userscript matches src/.');
} else {
  writeFileSync(target, output);
  console.log('Built userscript/slim-search-highlight.user.js');
}
