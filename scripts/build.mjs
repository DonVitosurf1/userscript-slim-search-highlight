import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(readFileSync(path.join(root, 'src/manifest.json'), 'utf8'));
const source = name => readFileSync(path.join(root, 'src', name), 'utf8').trimEnd();
const license = readFileSync(path.join(root, 'LICENSE'), 'utf8').trimEnd();
const licenseComment = license.split('\n').map(line => line ? `// ${line}` : '//').join('\n');
const sections = manifest.parts.map(name => {
  const body = source(name).split('\n').map(line => line ? '    ' + line : '').join('\n');
  return `    // Source: src/${name}\n${body}`;
});
const output = `${source(manifest.header)}\n\n${licenseComment}\n\n// Generated by scripts/build.mjs. Edit src/ and run npm run build.\n(function () {\n    'use strict';\n\n${sections.join('\n\n')}\n})();\n`;
const target = path.join(root, 'userscript/slim-search-highlight.user.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('Generated userscript is stale. Run npm run build.');
    process.exitCode = 1;
  } else console.log('Generated userscript matches src/.');
} else {
  writeFileSync(target, output);
  console.log('Built userscript/slim-search-highlight.user.js');
}
